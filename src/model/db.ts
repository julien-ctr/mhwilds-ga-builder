import type { Armor, ArmorKind, Charm, Decoration, GameData, Skill, Weapon, WeaponKind } from './types';
import { ARMOR_KINDS } from './types';

import versionJson from '../data/version.json';
import skillsJson from '../data/skills.json';
import armorJson from '../data/armor.json';
import setsJson from '../data/sets.json';
import decorationsJson from '../data/decorations.json';
import charmsJson from '../data/charms.json';
import weaponsJson from '../data/weapons.json';

/** Indexed, read-only view over the game data. */
export class Db {
  readonly data: GameData;
  readonly skills = new Map<number, Skill>();
  readonly armorById = new Map<number, Armor>();
  readonly armorByKind = new Map<ArmorKind, Armor[]>();
  readonly setNames = new Map<number, string>();
  readonly decorations: Decoration[];
  readonly decorationsById = new Map<number, Decoration>();
  readonly charmsById = new Map<number, Charm>();
  readonly weaponsById = new Map<number, Weapon>();
  readonly weaponsByKind = new Map<WeaponKind, Weapon[]>();

  constructor(data: GameData) {
    this.data = data;
    for (const s of data.skills) this.skills.set(s.id, s);
    for (const k of ARMOR_KINDS) this.armorByKind.set(k, []);
    for (const a of data.armor) {
      this.armorById.set(a.id, a);
      this.armorByKind.get(a.kind)!.push(a);
    }
    for (const s of data.sets) this.setNames.set(s.id, s.name);
    this.decorations = data.decorations;
    for (const d of data.decorations) this.decorationsById.set(d.id, d);
    for (const c of data.charms) this.charmsById.set(c.id, c);
    for (const w of data.weapons) {
      this.weaponsById.set(w.id, w);
      if (!this.weaponsByKind.has(w.kind)) this.weaponsByKind.set(w.kind, []);
      this.weaponsByKind.get(w.kind)!.push(w);
    }
  }

  skill(id: number): Skill | undefined {
    return this.skills.get(id);
  }

  maxLevel(id: number): number {
    return this.skills.get(id)?.maxLevel ?? 0;
  }
}

let defaultDb: Db | null = null;

/** The bundled French dataset (generated by `npm run sync`). */
export function getDb(): Db {
  if (!defaultDb) {
    defaultDb = new Db({
      version: versionJson.version,
      skills: skillsJson as GameData['skills'],
      armor: armorJson as GameData['armor'],
      sets: setsJson as GameData['sets'],
      decorations: decorationsJson as GameData['decorations'],
      charms: charmsJson as GameData['charms'],
      weapons: weaponsJson as unknown as GameData['weapons'],
    });
  }
  return defaultDb;
}
